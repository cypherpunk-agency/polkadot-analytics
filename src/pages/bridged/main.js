/**
 * The one thing this chart cannot show, said in words instead.
 *
 * The hatched remainder is the whole reason for this chart form — and here the six real
 * shortfalls are thousandths of a percent of supply, which at any sane width is the one-pixel
 * floor. Every bar therefore LOOKS full. Without this sentence a reader would take the picture
 * as evidence that everything reconciles, which is the exact opposite of the finding.
 */
function shortfallNote(holders) {
  const short = holders.assets.filter((asset) => !asset.reconciliation.holderSumMatchesSupply && Number(asset.supply) > 0)
  const empty = holders.assets.filter((asset) => asset.supply === '0').length
  const shares = short.map((asset) => (Number(asset.unaccounted) / Number(asset.supply)) * 100).sort((a, b) => a - b)

  const gap = shares.length
    ? `The ${shares.length} bars that do not reconcile fall short by between ${shares[0].toPrecision(2)} % and ${shares[shares.length - 1].toPrecision(2)} % of their own supply, which at this width is the one-pixel floor — the hatched remainder is drawn but it is not visible, so every bar here looks full. That finding is carried by the table below, not by the picture.`
    : 'Every bar is filled exactly by its segments.'

  const zero = empty
    ? ` ${empty} assets are registered with a supply of zero and draw an empty track: nothing is bridged in them at the moment, which is the chain saying so rather than a value this page could not read.`
    : ''

  return `${gap}${zero}`
}

