const wrapAnywhere = (node) => (node ? style(node, 'overflow-wrap:anywhere') : node)

/* ───────────────────────────────────────────────────────────────────────────── labelling ── */

/**
 * The amount column, and the one place a unit decision leaks into a format function.
 *
 * `segmentedRows` takes ONE formatter for every row, but eight of these assets have no
 * `Metadata` entry at all — nothing on chain says how many decimals they use — so their
 * amounts are raw `u128` integers while everybody else's are whole tokens. A raw integer put
 * through `compact()` reads "2100780034897481.00B", which is not a number anybody can hold in
 * their head and is one keystroke away from being mistaken for a scaled figure.
 *
 * So anything at or above 1e15 whole units is rendered in exponential form. That threshold is
 * a rendering choice, not a claim about the asset: the largest scaled supply here is 4.7e8 and
 * the smallest raw one is 3e15, so nothing crosses it by accident today. The row's sublabel
 * says "no decimals" independently, and the table below carries every exact digit.
 *
 * The BOTTOM end matters just as much and is quieter. `compact()` sends anything under ten
 * through `toFixed(2)`, so a real balance of 0.00022022 LBTC renders as "0.00" — a number that
 * reads as nothing next to a bar drawn at full width. On this site `null` is not `0`, and
 * neither is "small": below 0.01 the value keeps three significant figures instead.
 */
function amount(value) {
  const n = Number(value) || 0
  const abs = Math.abs(n)
  if (abs === 0) return '0'
  if (abs >= 1e15) return n.toExponential(2)
  if (abs < 0.01) return n.toPrecision(3)
  return compact(n)
}

/**
 * A raw integer balance rendered EXACTLY in whole units, by moving the decimal point rather
 * than by dividing.
 *
 * This is for the reconciliation column, where the exactness is the argument. `compact()` turns
 * the 11.15 USDC gap into "11" and the whole of the USDT finding — that the gap is *exactly*
 * 15.000000, arriving in one block — cannot be made in a column that has rounded it. Float
 * division cannot be trusted either: 91,090,925,517 at twelve decimals comes back as
 * 0.091090925518, one digit different from what the chain stores.
 *
 * With no decimals on chain there is nothing to shift, so the raw integer is returned as-is.
 */
function exactUnits(raw, decimals) {
  const digits = String(raw)
  if (decimals === null || decimals === undefined) return digits
  const negative = digits.startsWith('-')
  const body = (negative ? digits.slice(1) : digits).padStart(decimals + 1, '0')
  const whole = BigInt(body.slice(0, body.length - decimals)).toLocaleString('en-US')
  const fraction = decimals ? body.slice(body.length - decimals).replace(/0+$/, '') : ''
  return `${negative ? '-' : ''}${whole}${fraction ? `.${fraction}` : ''}`
}

/** The ERC-20 the location points at, already shortened by the source module. */
function contractOf(locationText) {
  const match = /AccountKey20\((0x[0-9a-fA-F…]+)\)/.exec(locationText ?? '')
  return match ? match[1] : null
}

/**
 * What to call an asset. A symbol when the chain provides one — and for the eight that have no
 * metadata, the contract address, because "unknown" eight times over is a list of one thing.
 */
const assetLabel = (asset) => asset.symbol ?? contractOf(asset.locationText) ?? shortAddr(asset.locationHex, 8, 6)

/** "Ethereum mainnet" is what the source module calls it; the bar row has seven rems. */
const networkShort = (asset) => (asset.networkLabel ?? asset.network ?? dash).replace(/ mainnet$/, '')

const scaledAsset = (asset) => asset.decimals !== null

/** A supply, in the unit the chain actually supports for this asset — raw when it supports none. */
const supplyText = (asset) => (scaledAsset(asset) ? amount(asset.supplyScaled) : asset.supply)

/* ──────────────────────────────────────────────────────────────────────── the chart data ── */

/**
 * The series, in a FIXED order that the row filtering never disturbs — colour follows the
 * series slot, not the rank.
 *
 * Asset Hub itself leads, because it is the one segment present on almost every row and it is
 * not a bridge destination: it is what has not left. The parachains follow in the order the
 * source module ranked them, so the ninth and beyond fall into the grey overflow slot, which
 * is the right way round — an overflowing tail should be the smallest holders, never the
 * category the whole page is about.
 */
const buildSeries = (chains) => [
  { label: 'Held on Asset Hub', key: 'asset-hub' },
  ...chains.map((chain) => ({ label: chain.chainName, key: chain.paraId })),
]

/**
 * One row per bridged asset. `total` is the pallet's own `supply`; `segments` are the swept
 * holder balances. They are passed SEPARATELY and the chart checks them — summing the segments
 * and calling that the total would make every row reconcile by construction, which is the one
 * thing this page must not do.
 *
 * Every value in a row comes from the same unit: scaled where the chain says how, raw integers
 * where it does not. Never both in one bar.
 */
function buildRows(assets, holdings, series) {
  const byAsset = new Map()
  for (const holding of holdings) {
    const perChain = byAsset.get(holding.assetKey) ?? new Map()
    const value = holding.amountScaled ?? Number(holding.amount)
    perChain.set(holding.paraId, (perChain.get(holding.paraId) ?? 0) + value)
    byAsset.set(holding.assetKey, perChain)
  }

  return assets.map((asset) => {
    const scaled = scaledAsset(asset)
    const perChain = byAsset.get(asset.locationHex) ?? new Map()
    const segments = series.map((entry) =>
      entry.key === 'asset-hub'
        ? (scaled ? asset.onAssetHubAccountsScaled : Number(asset.onAssetHubAccounts)) ?? 0
        : perChain.get(entry.key) ?? 0,
    )

    return {
      label: assetLabel(asset),
      sublabel: scaled ? networkShort(asset) : 'no decimals',
      // Ignored by `segmentedRows`, kept for this page: whether the row is in whole tokens or
      // in raw integers. Re-deriving it later by comparing the sublabel against a magic string
      // is the kind of thing that survives a copy-edit and then silently stops being true.
      scaled,
      total: scaled ? asset.supplyScaled : Number(asset.supply),
      segments,
      note: `${formatCount(asset.accountsClaimed)} holder account${asset.accountsClaimed === 1 ? '' : 's'} on Asset Hub, all of them swept`,
    }
  })
}

/**
 * Sorted by how WIDELY an asset is distributed, then by how many accounts hold it — both
 * unit-free, because the bars are unit-free. Sorting a mixed-unit list by supply would put
 * 473 million MYTH above 471 WETH and imply a ranking that does not exist without prices.
 */
function sortAssets(assets, rank = (asset) => asset) {
  return [...assets].sort((a, b) => {
    const left = rank(a) ?? {}
    const right = rank(b) ?? {}
    return (
      (right.chains ?? 0) - (left.chains ?? 0) ||
      (right.accountsClaimed ?? 0) - (left.accountsClaimed ?? 0) ||
      assetLabel(a).localeCompare(assetLabel(b))
    )
  })
}

/* ───────────────────────────────────────────────────────────────────────────────── render ── */

function render(host, [inventory, holders, valued]) {
  clear(host)

  if (!inventory.bridged.length) {
    append(
      host,
      notice(
        'warning',
        'Asset Hub has no bridged assets registered',
        'The chain answered and its `ForeignAssets` registry contains nothing with `parents: 2`. That is what the chain says right now; it is not a failure to read it.',
      ),
    )
    return
  }

  const series = buildSeries(holders.chains)
  const rows = buildRows(sortAssets(holders.assets), holders.holdings, series)

  append(
    host,
    // The page's subject leads: what is bridged in, in dollars. Decision 0011 — a dashboard
    // opens on the thing its title names, under at most a title and a sentence or two.
    valueStats(inventory, valued),
    livenessBanner([valued.ok ? valued.data.meta?.liveness : null, inventory.meta?.liveness, holders.meta?.liveness]),
    anomalyNotice(inventory),
    valueCard(valued),
    unpricedCard(valued),
    inventoryCard(inventory, holders),
    issuedCard(inventory),
    // Composition, and it closes the page rather than opening it. Every bar here is the same
    // length by construction and that reads as broken until you have read the caption; it is a
    // real answer to a different question, and a different question belongs further down.
    distributionCard(rows, series, holders, valued.ok ? valued.data.totals.priced : null),
    reconciliationCard(holders),
    notesSection(inventory, holders, valued),
  )
}

